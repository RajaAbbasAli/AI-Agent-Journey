print("===== Arithmetic Operators =====")

a = 20
b = 6

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Power:", a ** 2)
print("Floor Division:", a // b)

print("===== Comparison Operators =====")

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

print("===== Assignment Operators =====")

score = 10
score += 5
print(score)

score -= 2
print(score)

print("===== Logical Operators =====")

age = 20
verified = True

print(age >= 18 and verified)
print(age >= 18 or False)
print(not verified)